// M31e: builds packages/types (@midi-qol/types) from the declarations `npm run generate:types` emits into types/.
// usage: node tools/build-types-package.mjs (npm run types runs both). Not published: the package is private until
// midi-next is released (then: remove "private" and npm publish from packages/types).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const pkgDir = path.join(root, "packages", "types");
const dist = path.join(pkgDir, "dist");
const from = path.join(root, "types");
if (!fs.existsSync(path.join(from, "module", "api", "public.d.ts"))) {
  console.error("types/module/api/public.d.ts missing: run npm run generate:types first");
  process.exit(1);
}
fs.rmSync(dist, { recursive: true, force: true });
fs.cpSync(from, dist, { recursive: true, filter: src => !src.endsWith("tsconfig.json") });
const midi = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const fvtt = midi.devDependencies?.["fvtt-types"];
const pkg = {
  name: "@midi-qol/types",
  version: midi.version,
  private: true,
  description: "TypeScript types for midi-qol's public contract: its services, steps, entries, cues, outcomes and requests",
  types: "index.d.ts",
  files: ["index.d.ts", "dist", "README.md"],
  peerDependencies: { "fvtt-types": fvtt ?? "*" },
  license: "MIT"
};
fs.writeFileSync(path.join(pkgDir, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
fs.writeFileSync(path.join(pkgDir, "index.d.ts"), `// @midi-qol/types ${midi.version}: midi-qol's public contract (generated by tools/build-types-package.mjs)
/// <reference path="./dist/globals.d.ts" />
export * from "./dist/module/api/public.js";
`);
console.log(`packages/types: @midi-qol/types ${midi.version} built from types/`);
